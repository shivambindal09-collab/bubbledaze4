-- BUBBLEDAZE website database setup
-- Run the entire script in Supabase Dashboard > SQL Editor.

create table if not exists public.products (
  id bigint generated by default as identity primary key,
  name text not null,
  description text not null default '',
  price numeric(10,2),
  image_url text,
  badge text default 'BUBBLEDAZE',
  is_active boolean not null default true,
  sort_order integer not null default 0,
  created_at timestamptz not null default now()
);

create table if not exists public.contact_messages (
  id bigint generated by default as identity primary key,
  name text not null,
  contact text not null,
  subject text not null default 'General enquiry',
  message text not null,
  created_at timestamptz not null default now()
);

create table if not exists public.product_enquiries (
  id bigint generated by default as identity primary key,
  product_name text not null,
  name text not null,
  contact text not null,
  message text not null default '',
  created_at timestamptz not null default now()
);

alter table public.products enable row level security;
alter table public.contact_messages enable row level security;
alter table public.product_enquiries enable row level security;

-- Public visitors can only see active products.
drop policy if exists "Public can read active products" on public.products;
create policy "Public can read active products"
  on public.products for select to anon, authenticated
  using (is_active = true);

-- Public visitors can submit messages/enquiries but cannot read them back.
drop policy if exists "Public can submit contact messages" on public.contact_messages;
create policy "Public can submit contact messages"
  on public.contact_messages for insert to anon, authenticated
  with check (
    char_length(name) between 1 and 80 and
    char_length(contact) between 3 and 120 and
    char_length(message) between 1 and 1200
  );

drop policy if exists "Public can submit product enquiries" on public.product_enquiries;
create policy "Public can submit product enquiries"
  on public.product_enquiries for insert to anon, authenticated
  with check (
    char_length(product_name) between 1 and 120 and
    char_length(name) between 1 and 80 and
    char_length(contact) between 3 and 120 and
    char_length(message) <= 800
  );

grant select on public.products to anon, authenticated;
grant insert on public.contact_messages to anon, authenticated;
grant insert on public.product_enquiries to anon, authenticated;

